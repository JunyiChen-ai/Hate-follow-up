"""Acquire actual media inputs; no model predictions, GT or target adaptation."""
import argparse
import json
import logging
import os
import socket
import sys
import time
from inputs import ROOT,SPEC,CACHE,selected_rows,validate_input
from source_frames import acquire


def main():
    pipeline_start=time.perf_counter()
    ap=argparse.ArgumentParser();ap.add_argument('--smoke',action='store_true');args=ap.parse_args()
    out=ROOT/'runs/20261006_m1_rekv'/('source_frames_smoke' if args.smoke else 'source_frames_main')
    out.mkdir(parents=True,exist_ok=True)
    logging.basicConfig(level=logging.INFO,format='%(asctime)s %(message)s',handlers=[logging.FileHandler(out/'run.log'),logging.StreamHandler()])
    logging.info('host %s',socket.gethostname());(out/'run.pid').write_text(str(os.getpid()))
    config=dict(host=socket.gethostname(),date=time.strftime('%Y-%m-%d'),spec=SPEC,GT_read=False,smoke=args.smoke,
        source='experiments/20261006_m1_rekv/{extract_frames,source_frames}.py;2026-10-06',command='python -u '+' '.join(sys.argv))
    (out/'config.json').write_text(json.dumps(config,indent=2)+'\n')
    audit=dict(host=config['host'],date=config['date'],completed=False,scope='actual extraction attempt incl repeated validation/PNG/metadata I/O',videos=[])
    attempt=1
    while (out/f'pipeline_attempt_{attempt:04d}.json').exists():attempt+=1
    audit_path=out/f'pipeline_attempt_{attempt:04d}.json'
    try:
        rows=selected_rows(args.smoke)
        for number,row in enumerate(rows,1):
            video_start=time.perf_counter();entry=dict(dataset=row['dataset'],video_id=row['video_id'])
            folder=CACHE/row['dataset']/row['video_id'];folder.mkdir(parents=True,exist_ok=True);path=folder/'metadata.json'
            if path.exists():
                validation_start=time.perf_counter();meta=json.loads(path.read_text());validate_input(meta,row)
                entry.update(reused_input=True,validation_seconds=time.perf_counter()-validation_start,video_pipeline_seconds=time.perf_counter()-video_start)
                audit['videos'].append(entry);audit['elapsed_seconds']=time.perf_counter()-pipeline_start;audit_path.write_text(json.dumps(audit,indent=2)+'\n')
                logging.info('%d/%d current input reuse %s/%s',number,len(rows),row['dataset'],row['video_id']);continue
            acquisition_start=time.perf_counter();source=acquire(row,folder/'frames')
            entry.update(reused_input=False,acquisition_seconds=time.perf_counter()-acquisition_start)
            meta=dict(version=SPEC['version'],spec=SPEC,GT_read=False,host=socket.gethostname(),date=config['date'],
                dataset=row['dataset'],video_id=row['video_id'],source=source)
            validation_start=time.perf_counter();validate_input(meta,row);entry['validation_seconds']=time.perf_counter()-validation_start
            temporary=folder/'metadata.partial';temporary.write_text(json.dumps(meta)+'\n');temporary.replace(path)
            entry['video_pipeline_seconds']=time.perf_counter()-video_start;audit['videos'].append(entry)
            audit['elapsed_seconds']=time.perf_counter()-pipeline_start;audit_path.write_text(json.dumps(audit,indent=2)+'\n')
            logging.info('%d/%d %s/%s actualframes=%d',number,len(rows),row['dataset'],row['video_id'],len(source['selected_indices']))
        (CACHE/'PROVENANCE.md').write_text('# Actual source frames for layer-wise video KV retrieval\n\n'
            'Generated by experiments/20261006_m1_rekv/extract_frames.py andsource_frames.py,2026-10-06; actualhost/date/command inrunconfig andpervideo metadata. '
            'Actualrawpaths,containerorigin,decodedPTS/indices/PNGpixels,0.5fps targets/dedup/missing are preserved. '
            'Evaluation remains4fps; noGT/labels/modelprediction or contentdigests.\n')
        logging.info('SOURCE_FRAMES_DONE coverage=%d',len(rows))
        audit['completed']=True
    finally:
        audit['elapsed_seconds']=time.perf_counter()-pipeline_start
        audit_path.write_text(json.dumps(audit,indent=2)+'\n')


if __name__=='__main__':main()
