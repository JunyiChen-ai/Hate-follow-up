#!/usr/bin/env python3
"""Tables of the paper re-decode (README §3). Reads only the evaluator's metrics.json of each arm and the bootstrap
summaries written by analyze_dvd.py / within_boot.py; writes runs/20261101_paper_redecode/tables.md.
Old values are the r6-reader numbers quoted in the paper (calibrated key where the paper used it), with their sources.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "runs/20261101_paper_redecode"
SETS = {"HateMM": "main", "HateClipSeg": "main", "DeHate": "dehate"}
DS = ["HateMM", "HateClipSeg", "DeHate"]
IDX = {"roc": 0, "pr": 1, "within": 2}


def met(arm, ds):
    p = OUT / SETS[ds] / arm / "metrics.json"
    ev = [x for x in json.load(open(p))["per_dataset"] if x["dataset"] == ds][0]
    return ev


def three(arm, ds):
    ev = met(arm, ds)
    return ev["frame_ROC_AUC"], ev["frame_PR_AUC"], ev["within_video_macro_ROC_AUC"]


def wboot(sub, ds, arm, base):
    s = json.load(open(OUT / SETS[ds] / sub / "summary.json"))
    return s[f"{ds}:{arm}-{base}"]


def dboot(sub, ds, arm):
    s = json.load(open(OUT / SETS[ds] / sub / "summary.json"))
    return s[f"{ds}:{arm}"]["diff_vs_base"]


def fmt(d, lo=None, hi=None):
    s = f"{d:+.4f}"
    if lo is not None:
        s += f" [{lo:+.3f}, {hi:+.3f}]" + ("*" if lo > 0 or hi < 0 else "")
    return s


# old values (r6 reads): within or pooled delta per corpus, and the source
OLD = {
    "nocoupling": ((-.1141, -.0572, -.0205), "twolevel §20.1 analysis_final/table.txt; DeHate 20260928_infer §12.1 abl_nocoupling"),
    "k1": ((-.0302, -.0088, -.0157), "twolevel §20.1; DeHate abl_k1"),
    "fixed80": ((+.0017, +.0024, +.0108), "r3_m2 - final_m2 (twolevel §19.3); DeHate abl_fixed80 (paper prints -.002 / -.002 / +.011)"),
    "sharedchain": ((-.0074, -.0425, -.0131), "twolevel §20.1; DeHate abl_sharedchain"),
    "rawscale": ((+.0113, +.0114, -.0097), "twolevel §20.1; DeHate abl_rawscale"),
    "linstd": ((-.0096, -.0243, -.0140), "diag_lin_or_k4 - r2_noleak; DeHate abl_linstd - abl_r2nl (paper prints +.010 / +.024 / -.014)"),
    "nokey": ((-.3253, -.1469, -.1503), "pooled ROC, final_nokey - final_m2 (calibrated key); DeHate abl_nokey - final_m2"),
    "norank": ((-.2508, -.1373, -.1431), "within .5 - final_m2"),
}


def main():
    L = []
    L.append("# Paper re-decode tables (development-selected; generated by summarize.py)\n")
    L.append("Interval: 95 % paired bootstrap over videos (4000 draws). Within: within_boot.py (copy of analyze.py); "
             "pooled: analyze_dvd.py. `*` = interval excludes 0.\n")
    # ---------------------------------------------------------------- ablation
    L.append("## Task 1. Decoder and integrator ablations (arm - full method)\n")
    L.append("| removed or replaced | arm vs base | metric | " + " | ".join(f"{d} old | {d} new [95 %]" for d in DS) + " |")
    L.append("|---|---|---|" + "---|---|" * 3)
    rows = [("temporal coupling (independent cells)", "nocoupling", "m2", "within"),
            ("minimum length k = 1", "k1", "m2", "within"),
            ("mean length fixed at 80 s (--bma-fixed 80)", "fixed80", "m2", "within"),
            ("one shared chain", "sharedchain", "m2", "within"),
            ("normal scores off (raw reads into EM)", "rawscale", "m2", "within"),
            ("EM emissions -> reads / corpus s.d., fixed 80 s chain (old setting)", "linstd", "r2nl", "within"),
            ("video term removed", "nokey", "m2", "roc"),
            ("within term removed", "norank", "m2", "within")]
    for name, arm, base, mtr in rows:
        cells = []
        for k, ds in enumerate(DS):
            new = three(arm, ds)[IDX[mtr]] - three(base, ds)[IDX[mtr]]
            if mtr == "within":
                sub = "analysis_within" if base == "m2" else "analysis_within_evidence_fixed80"
                d, lo, hi, _ = wboot(sub, ds, arm, base)
                assert abs(d - new) < 1e-9, (arm, ds, d, new)
                c = fmt(new, lo, hi)
            elif mtr == "roc":
                sub = "analysis_ablation"
                d, lo, hi = dboot(sub, ds, arm)[0]
                c = fmt(new, lo, hi)
            else:
                c = fmt(new)
            cells.append(f"{OLD[arm][0][k]:+.4f} | {c}")
        L.append(f"| {name} | {arm} - {base} | {mtr} | " + " | ".join(cells) + " |")
    L.append("\nExtra rows (not in the old table): EM emissions replaced under the current chain.\n")
    L.append("| replaced | arm vs base | " + " | ".join(DS) + " |")
    L.append("|---|---|---|---|---|")
    for name, arm, base, sub in [("EM -> normal scores / s.d. (everything else = method)", "lin_bma_nscore", "m2", "analysis_within"),
                                 ("EM -> raw reads / s.d. (pair: raw reads into EM)", "lin_bma_raw", "rawscale", "analysis_within_evidence_bma_raw")]:
        cells = []
        for ds in DS:
            d, lo, hi, _ = wboot(sub, ds, arm, base)
            cells.append(fmt(d, lo, hi))
        L.append(f"| {name} | {arm} - {base} | " + " | ".join(cells) + " |")
    L.append("\nPooled ROC / PR change of every ablation (analyze_dvd.py, base m2):\n")
    L.append("| arm | " + " | ".join(DS) + " |")
    L.append("|---|---|---|---|")
    for arm in ["nocoupling", "k1", "fixed80", "sharedchain", "rawscale", "lin_bma_nscore", "nokey", "norank"]:
        cells = []
        for ds in DS:
            dd = dboot("analysis_ablation", ds, arm)
            cells.append(f"ROC {fmt(*dd[0])}; PR {fmt(*dd[1])}")
        L.append(f"| {arm} | " + " | ".join(cells) + " |")
    L.append("\nAbsolute pooled ROC / PR / within of every arm:\n")
    L.append("| arm | " + " | ".join(DS) + " |")
    L.append("|---|---|---|---|")
    for arm in ["m2", "nocoupling", "k1", "fixed80", "fixed80_k4", "sharedchain", "rawscale", "r2nl", "linstd",
                "lin_bma_raw", "lin_bma_nscore", "nokey", "norank"]:
        L.append(f"| {arm} | " + " | ".join("{:.4f} / {:.4f} / {:.4f}".format(*three(arm, ds)) for ds in DS) + " |")
    # ---------------------------------------------------------------- smoothing
    L.append("\n## Task 2. Smoothing (within)\n")
    OLDS = {"nocoupling": (.6367, .5801, .6226), "gauss2": (.6758, .6221, None), "gauss4": (.6854, .6284, .6413),
            "gauss8": (.6877, .6312, .6468), "gauss16": (.6726, .6212, None), "m2": (.7508, .6373, .6431)}
    L.append("| time level | " + " | ".join(f"{d} old | {d} new" for d in DS) + " |")
    L.append("|---|" + "---|---|" * 3)
    for arm, name in [("nocoupling", "none (independent cells)"), ("gauss2", "Gaussian 2 s"), ("gauss4", "Gaussian 4 s"),
                      ("gauss8", "Gaussian 8 s"), ("gauss16", "Gaussian 16 s"), ("m2", "explicit-duration chain")]:
        L.append(f"| {name} | " + " | ".join(
            ("—" if OLDS[arm][k] is None else f"{OLDS[arm][k]:.4f}") + f" | {three(arm, ds)[2]:.4f}" for k, ds in enumerate(DS)) + " |")
    L.append("\nChain minus best sigma (best chosen per corpus on test within, which favours smoothing):\n")
    for ds in DS:
        best = max(["gauss2", "gauss4", "gauss8", "gauss16"], key=lambda a: three(a, ds)[2])
        d, lo, hi, n = wboot("analysis_within", ds, best, "m2")
        L.append(f"- {ds}: best {best}; chain - {best} = {fmt(-d, -hi, -lo)} ({n} videos)")
    # ---------------------------------------------------------------- modality
    L.append("\n## Task 3. Modality rows (within; vs two branches OR)\n")
    OLDM = {"speechonly": (.7378, .5781, .6525), "visualonly": (.6766, .5795, .5673), "m2": (.7508, .6373, .6431),
            "gate": (.7513, .6325, .6638)}
    L.append("| window branches | " + " | ".join(f"{d} old | {d} new | {d} new - OR [95 %]" for d in DS) + " |")
    L.append("|---|" + "---|---|---|" * 3)
    for arm, name in [("speechonly", "speech branch only"), ("visualonly", "visual branch only"),
                      ("m2", "two isolated branches, OR (method)"), ("gate", "two branches, per-video verdict gate")]:
        cells = []
        for k, ds in enumerate(DS):
            w = three(arm, ds)[2]
            if arm == "m2":
                cells.append(f"{OLDM[arm][k]:.4f} | {w:.4f} | —")
            else:
                d, lo, hi, _ = wboot("analysis_within", ds, arm, "m2")
                cells.append(f"{OLDM[arm][k]:.4f} | {w:.4f} | {fmt(d, lo, hi)}")
        L.append(f"| {name} | " + " | ".join(cells) + " |")
    L.append("\nPooled ROC / PR of the modality arms:\n")
    for arm in ["speechonly", "visualonly", "m2", "gate"]:
        L.append(f"- {arm}: " + "; ".join("{} {:.4f} / {:.4f}".format(ds, *three(arm, ds)[:2]) for ds in DS))
    # ---------------------------------------------------------------- intervals
    L.append("\n## Task 4. Interval output (--arm full, raw key)\n")
    OLDF = {"HateMM": ".8904 / .7133 / .7508; F1 .325 / .295 / .235", "HateClipSeg": ".7391 / .6779 / .6373; F1 .246 / .145 / .077",
            "DeHate": ".6947 / .1559 / .6431; F1 .178 / .133 / .105"}
    L.append("| corpus | old (final_full, calibrated key) | new pooled ROC / PR / within | F1@.3 / .5 / .7 | precision@.3 / .5 / .7 | recall@.3 / .5 / .7 | non-empty intervals |")
    L.append("|---|---|---|---|---|---|---|")
    for ds in DS:
        ev = met("full", ds)
        L.append(f"| {ds} | {OLDF[ds]} | {ev['frame_ROC_AUC']:.4f} / {ev['frame_PR_AUC']:.4f} / {ev['within_video_macro_ROC_AUC']:.4f} | "
                 + " / ".join(f"{ev[f'interval_F1@{t}']:.3f}" for t in ("0.3", "0.5", "0.7")) + " | "
                 + " / ".join(f"{ev[f'interval_precision@{t}']:.3f}" for t in ("0.3", "0.5", "0.7")) + " | "
                 + " / ".join(f"{ev[f'interval_recall@{t}']:.3f}" for t in ("0.3", "0.5", "0.7")) + f" | {ev.get('n_nonempty_intervals')} |")
    # ---------------------------------------------------------------- read sets
    L.append("\n## Task 5. Window-evidence inputs (current decoder, raw key)\n")
    L.append("| read set | " + " | ".join(f"{d} ROC / PR / within" for d in DS) + " |")
    L.append("|---|---|---|---|")
    for arm, name in [("rs_old", "old reader (r6)"), ("rs_frames", "frames only"), ("rs_words", "words only"), ("m2", "both (adopted)")]:
        L.append(f"| {name} | " + " | ".join("{:.4f} / {:.4f} / {:.4f}".format(*three(arm, ds)) for ds in DS) + " |")
    L.append("\nDifference to the old reader (analyze_dvd.py, base rs_old; ROC / PR / within):\n")
    for arm in ["rs_frames", "rs_words", "m2"]:
        L.append(f"- {arm}: " + "; ".join(f"{ds} " + " / ".join(fmt(*x) for x in dboot("analysis_readsets", ds, arm)) for ds in DS))
    # ---------------------------------------------------------------- key scale
    L.append("\n## Task 6. Video-term scale s (frame score = s K + centred rank)\n")
    L.append("| s | " + " | ".join(f"{d} ROC / PR / within" for d in DS) + " |")
    L.append("|---|---|---|---|")
    for s in ["100", "8", "4", "2", "1", "0.5", "0.25", "0.125"]:
        L.append(f"| {s} | " + " | ".join("{:.4f} / {:.4f} / {:.4f}".format(*three(f"s{s}", ds)) for ds in DS) + " |")
    if all((OUT / SETS[ds] / "old_s1" / "metrics.json").exists() for ds in DS):
        L.append("\nSame sweep on the old (r6) reads under the current decoder (stage extra):\n")
        L.append("| s | " + " | ".join(f"{d} ROC / PR / within" for d in DS) + " |")
        L.append("|---|---|---|---|")
        for s in ["100", "8", "4", "2", "1", "0.5", "0.25", "0.125"]:
            L.append(f"| {s} | " + " | ".join("{:.4f} / {:.4f} / {:.4f}".format(*three(f"old_s{s}", ds)) for ds in DS) + " |")
    L.append("\nPlumbing: s = 1 vs the method (m2), max |difference| of the three metrics: " + "; ".join(
        f"{ds} {max(abs(x - y) for x, y in zip(three('s1', ds), three('m2', ds))):.1e}" for ds in DS))
    L.append("Plumbing: fixed80 (--bma-fixed 80) vs fixed80_k4 (--k 4, fixed durations): " + "; ".join(
        f"{ds} {max(abs(x - y) for x, y in zip(three('fixed80', ds), three('fixed80_k4', ds))):.1e}" for ds in DS))
    (OUT / "tables.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
